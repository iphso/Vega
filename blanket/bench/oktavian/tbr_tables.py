def corr_matrix(upper):
    import numpy as np
    n = len(upper)
    C = np.eye(n)
    for i, row in enumerate(upper):
        for k, v in enumerate(row):
            C[i, i + 1 + k] = C[i + 1 + k, i] = v
    return C
