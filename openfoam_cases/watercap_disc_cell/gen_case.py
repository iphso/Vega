#!/usr/bin/env python3
"""Generate an OpenFOAM-10 case for one periodic disc period of a watercap disc-stack tube.

Geometry (same as StoneLab's DiscStackSection): grounded tube radius R, a thin coaxial disc
(radius rd, thickness t, square edge here -- StoneLab rounds it with radius t/2) centred at
z = s/2 in a cell 0 <= z <= s, cyclic in z. No mount rod (StoneLab has none either).
Air (StoneLab's rho = 1.15 kg/m^3, mu = 1.81e-5 Pa s) is driven by meanVelocityForce so the
flux through the tube is U * pi R^2 (the volume-average target Ubar is corrected for the disc
volume, which is the only place the cross-section changes).

Meshes: axisymmetric 5-degree wedge (default) or a 3-D sector with rotational cyclics
(--sector DEG --ntheta N) for DES/LES. --level m scales every cell count by m and every
wall-adjacent cell size by 1/m.

Usage: gen_case.py OUTDIR --design cold_spray-0126 [--level 1] [--solver simpleFoam|pimpleFoam]
       [--model kOmegaSST|kOmegaSSTDES|WALE] [--sector 0] [--ntheta 1] [--endTime T] [--np 1]
"""
import argparse, json, math, os, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
RHO, MU = 1.15, 1.81e-5
NU = MU / RHO

HDR = """/*--------------------------------*- C++ -*----------------------------------*\\
  =========                 |
  \\\\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox
   \\\\    /   O peration     | Version:  10   (generated by gen_case.py)
    \\\\  /    A nd           |
     \\\\/     M anipulation  |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    format      ascii;
    class       {cls};
    location    "{loc}";
    object      {obj};
}}
"""


def write(path, cls, loc, obj, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(HDR.format(cls=cls, loc=loc, obj=obj) + body)


def ratio_for(L, n, h):
    """Geometric ratio q with h (1 + q + ... + q^(n-1)) = L."""
    if h * n >= L:
        return 1.0
    lo, hi = 1.0 + 1e-12, 2.0
    while h * (hi ** n - 1) / (hi - 1) < L:
        hi *= 2
    for _ in range(200):
        q = 0.5 * (lo + hi)
        if h * (q ** n - 1) / (q - 1) < L:
            lo = q
        else:
            hi = q
    return q


def seg_fine_end(L, n, h, fine_at_start):
    """blockMesh expansion ratio (last/first) for n cells over L with size h at the fine end."""
    q = ratio_for(L, n, h)
    e = q ** (n - 1)
    return (1 / e if not fine_at_start else e), h * e    # (expansion, coarse cell size)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--design", default="cold_spray-0126")
    ap.add_argument("--level", type=float, default=1.0)
    ap.add_argument("--solver", default="simpleFoam")
    ap.add_argument("--model", default="kOmegaSST")
    ap.add_argument("--sector", type=float, default=0.0, help="3-D sector angle in degrees (0: 5-deg wedge)")
    ap.add_argument("--ntheta", type=int, default=1)
    ap.add_argument("--endTime", type=float, default=None)
    ap.add_argument("--dt", type=float, default=None)
    ap.add_argument("--maxCo", type=float, default=0.8)
    ap.add_argument("--np", type=int, default=1)
    ap.add_argument("--urelax", type=float, default=0.9)
    ap.add_argument("--trelax", type=float, default=0.7)
    ap.add_argument("--prelax", type=float, default=0.0, help=">0: plain SIMPLE with this p relaxation (else SIMPLEC)")
    ap.add_argument("--writeInterval", type=float, default=None)
    ap.add_argument("--avgStart", type=float, default=None)
    ap.add_argument("--rcoarse", type=float, default=1.0, help="extra factor on the radial/axial counts (3-D)")
    a = ap.parse_args()

    d = json.load(open(os.path.join(HERE, "designs_params.json")))[a.design]
    R, U, rd, t, s = d["R"], d["U"], d["rd"], d["t"], d["s"]
    m = a.level
    steady = a.solver == "simpleFoam"
    sector3d = a.sector > 0
    ang = math.radians(a.sector if sector3d else 5.0) / 2

    # ---------------- mesh parameters
    h_disc = 0.05e-3 / m           # first cell off the disc faces / edge
    h_wall = 0.10e-3 / m           # first cell off the tube wall
    nA = max(4, round(90 * m * a.rcoarse))      # axis -> disc edge
    nB = max(4, round(100 * m * a.rcoarse))     # disc edge -> wall (two-sided)
    nZ = max(4, round(70 * m * a.rcoarse))      # each half-period
    nT = max(2, round(6 * m))                   # across the disc thickness
    z1, z2 = s / 2 - t / 2, s / 2 + t / 2
    eA, cA = seg_fine_end(rd, nA, h_disc, fine_at_start=False)
    LB = R - rd
    eB1, cB1 = seg_fine_end(LB / 2, nB // 2, h_disc, fine_at_start=True)
    eB2, cB2 = seg_fine_end(LB / 2, nB - nB // 2, h_wall, fine_at_start=False)
    eZlo, cZ = seg_fine_end(z1, nZ, h_disc, fine_at_start=False)      # coarse at z=0, fine at disc bottom
    eZhi, _ = seg_fine_end(s - z2, nZ, h_disc, fine_at_start=True)
    gradB = f"(({0.5} {nB // 2 / nB:.6f} {eB1:.6g}) ({0.5} {1 - nB // 2 / nB:.6f} {eB2:.6g}))"

    rs = [0.0, rd, R]
    zs = [0.0, z1, z2, s]
    verts, vid = [], {}

    def V(ir, iz, side):            # side 0: +y (front), 1: -y (back)
        r, z = rs[ir], zs[iz]
        key = (ir, iz, 0 if r == 0 else side)
        if key not in vid:
            sg = 1 if side == 0 else -1
            vid[key] = len(verts)
            verts.append((r * math.cos(ang), sg * r * math.sin(ang), z))
        return vid[key]

    def hexv(ir, iz):
        f = [V(ir, iz, 0), V(ir + 1, iz, 0), V(ir + 1, iz + 1, 0), V(ir, iz + 1, 0)]
        b = [V(ir, iz, 1), V(ir + 1, iz, 1), V(ir + 1, iz + 1, 1), V(ir, iz + 1, 1)]
        return f + b

    nth = a.ntheta if sector3d else 1
    zgrad = [eZlo, 1, eZhi]
    nzs = [nZ, nT, nZ]
    blocks = []
    for ir in (0, 1):
        for iz in (0, 1, 2):
            if ir == 0 and iz == 1:
                continue                                   # the disc
            nr = nA if ir == 0 else nB
            gr = f"{eA:.6g}" if ir == 0 else gradB
            blocks.append(f"    hex ({' '.join(map(str, hexv(ir, iz)))}) ({nr} {nzs[iz]} {nth}) "
                          f"simpleGrading ({gr} {zgrad[iz]:.6g} 1)")

    def face(ir0, iz0, ir1, iz1, side_pair):
        # quad between corner (ir0,iz0)-(ir1,iz1) in the r-z plane, extruded front->back
        return None

    def rzface(p, q):               # face spanning r-z segment p->q, both sides
        (ir0, iz0), (ir1, iz1) = p, q
        return f"({V(ir0, iz0, 0)} {V(ir1, iz1, 0)} {V(ir1, iz1, 1)} {V(ir0, iz0, 1)})"

    def side_face(ir, iz, side):
        return "(" + " ".join(str(V(*c, side)) for c in [(ir, iz), (ir + 1, iz), (ir + 1, iz + 1), (ir, iz + 1)]) + ")"

    fluid = [(0, 0), (0, 2), (1, 0), (1, 1), (1, 2)]
    front = "\n".join("            " + side_face(ir, iz, 0) for ir, iz in fluid)
    back = "\n".join("            " + side_face(ir, iz, 1) for ir, iz in fluid)
    pf, pb = ("front", "back")
    if sector3d:
        side_patches = f"""    front
    {{
        type cyclic;
        neighbourPatch back;
        transform rotational;
        rotationAxis (0 0 1);
        rotationCentre (0 0 0);
        faces
        (
{front}
        );
    }}
    back
    {{
        type cyclic;
        neighbourPatch front;
        transform rotational;
        rotationAxis (0 0 1);
        rotationCentre (0 0 0);
        faces
        (
{back}
        );
    }}
"""
    else:
        side_patches = f"""    front
    {{
        type wedge;
        faces
        (
{front}
        );
    }}
    back
    {{
        type wedge;
        faces
        (
{back}
        );
    }}
"""
    edges = ""
    if sector3d:
        el = []
        for ir in (1, 2):
            for iz in range(4):
                r, z = rs[ir], zs[iz]
                el.append(f"    arc {V(ir, iz, 0)} {V(ir, iz, 1)} ({r:.9g} 0 {z:.9g})")
        edges = "\n".join(el)
    bm = f"""convertToMeters 1;

vertices
(
{chr(10).join(f'    ({x:.9g} {y:.9g} {z:.9g})' for x, y, z in verts)}
);

blocks
(
{chr(10).join(blocks)}
);

edges
(
{edges}
);

boundary
(
{side_patches}    tubeWall
    {{
        type wall;
        faces
        (
            {rzface((2, 0), (2, 1))}
            {rzface((2, 1), (2, 2))}
            {rzface((2, 2), (2, 3))}
        );
    }}
    disc
    {{
        type wall;
        faces
        (
            {rzface((0, 1), (1, 1))}
            {rzface((1, 2), (0, 2))}
            {rzface((1, 1), (1, 2))}
        );
    }}
    bottom
    {{
        type cyclic;
        neighbourPatch top;
        transform translational;
        separation (0 0 {-s:.9g});  // maps the neighbour (top) onto this patch
        faces
        (
            {rzface((0, 0), (1, 0))}
            {rzface((1, 0), (2, 0))}
        );
    }}
    top
    {{
        type cyclic;
        neighbourPatch bottom;
        transform translational;
        separation (0 0 {s:.9g});
        faces
        (
            {rzface((0, 3), (1, 3))}
            {rzface((1, 3), (2, 3))}
        );
    }}
    axis
    {{
        type empty;
        faces
        (
            {rzface((0, 0), (0, 1))}
            {rzface((0, 2), (0, 3))}
        );
    }}
);
"""
    os.makedirs(a.out, exist_ok=True)
    write(f"{a.out}/system/blockMeshDict", "dictionary", "system", "blockMeshDict", bm)

    # ---------------- physics
    V_fluid = math.pi * R ** 2 * s - math.pi * rd ** 2 * t
    Ubar = U * math.pi * R ** 2 * s / V_fluid
    write(f"{a.out}/constant/physicalProperties", "dictionary", "constant", "physicalProperties",
          f"viscosityModel  constant;\nnu              [0 2 -1 0 0 0 0] {NU:.9g};\n")
    if a.model in ("WALE", "Smagorinsky"):
        mt = f"""simulationType LES;
LES
{{
    model           {a.model};
    turbulence      on;
    printCoeffs     on;
    delta           cubeRootVol;
    cubeRootVolCoeffs {{ deltaCoeff 1; }}
}}
"""
    elif a.model == "laminar":
        mt = "simulationType laminar;\n"
    else:
        mt = f"""simulationType RAS;
RAS
{{
    model           {a.model};
    turbulence      on;
    printCoeffs     on;
}}
""" if "DES" not in a.model else f"""simulationType LES;
LES
{{
    model           {a.model};
    turbulence      on;
    printCoeffs     on;
    delta           cubeRootVol;
    cubeRootVolCoeffs {{ deltaCoeff 1; }}
}}
"""
    write(f"{a.out}/constant/momentumTransport", "dictionary", "constant", "momentumTransport", mt)
    write(f"{a.out}/system/fvConstraints", "dictionary", "system", "fvConstraints", f"""momentumForce
{{
    type            meanVelocityForce;
    selectionMode   all;
    Ubar            (0 0 {Ubar:.9g});
    relaxation      {0.2 if steady else 1.0};
}}
""")

    # ---------------- initial / boundary fields (pipe-like guesses)
    k0 = 1.5 * (0.05 * U) ** 2
    om0 = math.sqrt(k0) / (0.09 ** 0.25 * 0.07 * R)
    side_bc = "        type cyclic;" if sector3d else "        type wedge;"

    def field(name, cls, dim, internal, wall_bc):
        body = f"""dimensions      {dim};

internalField   {internal};

boundaryField
{{
    "(front|back)"
    {{
{side_bc}
    }}
    "(bottom|top)"
    {{
        type cyclic;
    }}
    axis
    {{
        type empty;
    }}
    "(tubeWall|disc)"
    {{
{wall_bc}
    }}
}}
"""
        write(f"{a.out}/0/{name}", cls, "0", name, body)

    field("U", "volVectorField", "[0 1 -1 0 0 0 0]", f"uniform (0 0 {U:.6g})", "        type noSlip;")
    field("p", "volScalarField", "[0 2 -2 0 0 0 0]", "uniform 0", "        type zeroGradient;")
    if a.model != "laminar":
        if a.model in ("WALE", "Smagorinsky"):
            field("nut", "volScalarField", "[0 2 -1 0 0 0 0]", "uniform 0", "        type zeroGradient;")   # wall-resolved LES nu_t->0 via WALE
            field("k", "volScalarField", "[0 2 -2 0 0 0 0]", "uniform 0", "        type fixedValue;\n        value uniform 0;")
        else:
            field("k", "volScalarField", "[0 2 -2 0 0 0 0]", f"uniform {k0:.6g}",
                  "        type kqRWallFunction;\n        value uniform 1e-10;")
            field("omega", "volScalarField", "[0 0 -1 0 0 0 0]", f"uniform {om0:.6g}",
                  "        type omegaWallFunction;\n        value uniform 1;")
            field("nut", "volScalarField", "[0 2 -1 0 0 0 0]", "uniform 0",
                  "        type nutUSpaldingWallFunction;\n        value uniform 0;")

    # ---------------- control / schemes / solution
    end = a.endTime if a.endTime is not None else (8000 if steady else 1.0)
    wi = a.writeInterval if a.writeInterval is not None else (1000 if steady else 0.05)
    dt = a.dt if a.dt is not None else (1 if steady else 0.2 * h_disc / U)
    avg = a.avgStart if a.avgStart is not None else end / 2
    xprobe = []
    # probes in the wake (downstream = +z) and upstream, mid-gap radius, the disc edge shear layer
    for zz in (z2 + 0.25 * (s - z2), z2 + 0.5 * (s - z2), z1 - 0.25 * z1):
        for rr in (0.25 * rd, 0.75 * rd, rd, 0.5 * (rd + R)):
            xprobe.append(f"            ({rr * math.cos(0):.6g} 0 {zz:.6g})")
    fo_avg = "" if steady else f"""    fieldAverage1
    {{
        type            fieldAverage;
        libs            ("libfieldFunctionObjects.so");
        writeControl    writeTime;
        timeStart       {avg};
        fields
        (
            U {{ mean on; prime2Mean on; base time; }}
            p {{ mean on; prime2Mean off; base time; }}
            {"nut { mean on; prime2Mean off; base time; }" if a.model != "laminar" else ""}
        );
    }}
    probes1
    {{
        type            probes;
        libs            ("libsampling.so");
        writeControl    timeStep;
        writeInterval   {1 if not sector3d else 2};
        fields          (U p);
        probeLocations
        (
{chr(10).join(xprobe)}
        );
    }}
"""
    write(f"{a.out}/system/controlDict", "dictionary", "system", "controlDict", f"""application     {a.solver};
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {end};
deltaT          {dt:.6g};
writeControl    {"timeStep" if steady else "adjustableRunTime"};
writeInterval   {wi};
purgeWrite      {2 if steady else 0};
writeFormat     ascii;
writePrecision  8;
writeCompression off;
timeFormat      general;
timePrecision   8;
runTimeModifiable true;
adjustTimeStep  {"no" if steady else "yes"};
maxCo           {a.maxCo};

functions
{{
    forcesDisc
    {{
        type            forces;
        libs            ("libforces.so");
        writeControl    timeStep;
        writeInterval   {10 if steady else 1};
        patches         (disc);
        rho             rhoInf;
        rhoInf          {RHO};
        CofR            (0 0 {s / 2:.6g});
    }}
    forcesWall
    {{
        type            forces;
        libs            ("libforces.so");
        writeControl    timeStep;
        writeInterval   {10 if steady else 1};
        patches         (tubeWall);
        rho             rhoInf;
        rhoInf          {RHO};
        CofR            (0 0 {s / 2:.6g});
    }}
    yPlus1
    {{
        type            yPlus;
        libs            ("libfieldFunctionObjects.so");
        writeControl    writeTime;
    }}
    residuals1
    {{
        type            residuals;
        libs            ("libutilityFunctionObjects.so");
        fields          (U p {"k omega" if a.model.startswith("kOmega") else ""});
    }}
{fo_avg}}}
""")
    if steady:
        conv = "bounded Gauss"
        div_u = f"{conv} linearUpwind grad(U)"
        div_t = f"{conv} limitedLinear 1"
        ddt = "steadyState"
    else:
        div_u = "Gauss LUST grad(U)" if (sector3d or a.model in ("WALE", "kOmegaSSTDES")) else "Gauss linearUpwind grad(U)"
        div_t = "Gauss limitedLinear 1"
        ddt = "backward"
    write(f"{a.out}/system/fvSchemes", "dictionary", "system", "fvSchemes", f"""ddtSchemes {{ default {ddt}; }}
gradSchemes
{{
    default         Gauss linear;
    grad(U)         cellLimited Gauss linear 1;
}}
divSchemes
{{
    default         none;
    div(phi,U)      {div_u};
    div(phi,k)      {div_t};
    div(phi,omega)  {div_t};
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}}
laplacianSchemes {{ default Gauss linear corrected; }}
interpolationSchemes {{ default linear; }}
snGradSchemes {{ default corrected; }}
wallDist {{ method meshWave; }}
""")
    if steady:
        alg = ("""SIMPLE
{
    nNonOrthogonalCorrectors 0;
    consistent      CONSISTENT;
    pRefCell        0;
    pRefValue       0;
    residualControl
    {
        p               1e-6;
        U               1e-7;
        "(k|omega)"     1e-7;
    }
}
relaxationFactors
{
    PFIELDS
    equations
    {
        U               URELAX;
        ".*"            TRELAX;
    }
}
""").replace("URELAX", str(a.urelax)).replace("CONSISTENT", "no" if a.prelax > 0 else "yes") \
            .replace("PFIELDS", f"fields {{ p {a.prelax}; }}" if a.prelax > 0 else "").replace("TRELAX", str(a.trelax))
    else:
        alg = """PIMPLE
{
    nOuterCorrectors 2;
    nCorrectors     2;
    nNonOrthogonalCorrectors 0;
    pRefCell        0;
    pRefValue       0;
}
relaxationFactors { equations { ".*" 1; } }
"""
    write(f"{a.out}/system/fvSolution", "dictionary", "system", "fvSolution", f"""solvers
{{
    p
    {{
        solver          GAMG;
        smoother        GaussSeidel;
        tolerance       1e-8;
        relTol          {0.05 if steady else 0.01};
    }}
    pFinal {{ $p; relTol 0; tolerance 1e-7; }}
    "(U|k|omega)"
    {{
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-9;
        relTol          0.05;
    }}
    "(U|k|omega)Final" {{ $U; relTol 0; tolerance 1e-8; }}
}}
{alg}""")
    if a.np > 1:
        write(f"{a.out}/system/decomposeParDict", "dictionary", "system", "decomposeParDict",
              f"numberOfSubdomains {a.np};\nmethod scotch;\n")
    meta = dict(vars(a), R=R, U=U, rd=rd, t=t, s=s, Ubar=Ubar, V_fluid_full=V_fluid, nu=NU, rho=RHO,
                wedge_or_sector_rad=2 * ang, nA=nA, nB=nB, nZ=nZ, nT=nT, h_disc=h_disc, h_wall=h_wall,
                coarse_axis=cA, coarse_mid_B=max(cB1, cB2), coarse_z=cZ,
                cells=(nA * 2 * nZ + nB * (2 * nZ + nT)) * nth)
    json.dump(meta, open(f"{a.out}/case_meta.json", "w"), indent=1)
    shutil.copy(os.path.join(HERE, "Allrun.foam"), f"{a.out}/Allrun.foam")
    print(json.dumps({k: meta[k] for k in ("cells", "coarse_axis", "coarse_mid_B", "coarse_z", "Ubar")}))


if __name__ == "__main__":
    main()
